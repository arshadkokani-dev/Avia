"use client";

import {
  useCallback,
  useEffect,
  useRef,
  useState,
  type FormEvent,
} from "react";
import { apiRequest } from "../../lib/api";
import "./ai-coach.css";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";

type Message = {
  id: string;
  role: "user" | "assistant";
  content: string;
  createdAt: string;
};

type Conversation = {
  id: string;
  title: string;
  createdAt: string;
  updatedAt: string;
  messages: { content: string; role: string }[];
};

type ContextSummary = {
  goals: number;
  urgentGoals: number;
  plannedTasks: number;
  pendingTasks: number;
  habits: number;
  pendingHabits: number;
  journalIncluded: boolean;
};

type SendResponse = {
  userMessage: Message;
  assistantMessage: Message;
  contextSummary: ContextSummary;
};

type SpeechLanguage = "en-IN" | "hi-IN" | "mr-IN";

type SpeechRecognitionResultLike = {
  isFinal: boolean;
  0: {
    transcript: string;
  };
};

type SpeechRecognitionEventLike = {
  resultIndex: number;
  results: ArrayLike<SpeechRecognitionResultLike>;
};

type SpeechRecognitionLike = {
  lang: string;
  continuous: boolean;
  interimResults: boolean;
  onresult: ((event: SpeechRecognitionEventLike) => void) | null;
  onerror: ((event: { error: string }) => void) | null;
  onend: (() => void) | null;
  start: () => void;
  stop: () => void;
  abort: () => void;
};

type SpeechRecognitionConstructor = new () => SpeechRecognitionLike;

type SpeechWindow = Window & {
  SpeechRecognition?: SpeechRecognitionConstructor;
  webkitSpeechRecognition?: SpeechRecognitionConstructor;
};

const suggestions = [
  "Review my current goals and suggest what to prioritize.",
  "Help me create a realistic plan for tomorrow.",
  "How can I improve my habit consistency?",
  "Analyze my recent progress and suggest improvements.",
];

// Render a copyable plan generated by AVIA Coach.
function PlanCopyBlock({ children }: { children: React.ReactNode }) {
  const [copied, setCopied] = useState(false);

  const planText = String(children).replace(/\n$/, "");

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(planText);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setCopied(false);
    }
  };

  return (
    <div className="coach-plan-card">
      <div className="coach-plan-header">
        <div>
          <span className="coach-plan-icon">✦</span>
          <strong>AVIA PLAN</strong>
        </div>

        <button type="button" onClick={() => void handleCopy()}>
          {copied ? "Copied ✓" : "Copy plan"}
        </button>
      </div>

      <pre className="coach-plan-content">
        {planText}
      </pre>
    </div>
  );
}

export default function AICoachPage() {
  const [tab, setTab] = useState<"chat" | "history">("chat");
  const [conversations, setConversations] = useState<Conversation[]>([]);
  const [activeId, setActiveId] = useState<string | null>(null);
  const [messages, setMessages] = useState<Message[]>([]);
  const [input, setInput] = useState("");
  const [includeJournal, setIncludeJournal] = useState(false);
  const [loading, setLoading] = useState(false);
  const [loadingHistory, setLoadingHistory] = useState(true);
  const [error, setError] = useState("");
  const [contextSummary, setContextSummary] =
    useState<ContextSummary | null>(null);
  const [editingMessageId, setEditingMessageId] = useState<string | null>(null);

  const [speechLanguage, setSpeechLanguage] =
    useState<SpeechLanguage>("en-IN");

  const [isListening, setIsListening] = useState(false);
  const [voiceError, setVoiceError] = useState("");

  const recognitionRef = useRef<SpeechRecognitionLike | null>(null);
  const voiceBaseRef = useRef("");
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    if (!editingMessageId) return;

    const textarea = inputRef.current;

    if (textarea) {
      textarea.scrollIntoView({
        behavior: "smooth",
        block: "center",
      });

      textarea.focus({ preventScroll: true });

      const cursorPosition = textarea.value.length;

      textarea.setSelectionRange(cursorPosition, cursorPosition);
    }
  }, [editingMessageId]);

  function startVoiceInput() {
    if (loading || isListening) return;

    const speechWindow = window as SpeechWindow;

    const Recognition =
      speechWindow.SpeechRecognition ??
      speechWindow.webkitSpeechRecognition;

    if (!Recognition) {
      setVoiceError(
        "Voice input is not supported in this browser. Try Chrome.",
      );
      return;
    }

    setVoiceError("");
    voiceBaseRef.current = input.trim();

    const recognition = new Recognition();

    recognition.lang = speechLanguage;
    recognition.continuous = false;
    recognition.interimResults = true;

    recognition.onresult = (event) => {
      let transcript = "";

      for (let index = 0; index < event.results.length; index += 1) {
        transcript += `${event.results[index][0].transcript} `;
      }

      setInput(
        [voiceBaseRef.current, transcript.trim()]
          .filter(Boolean)
          .join(" "),
      );
    };

    recognition.onerror = (event) => {
      setVoiceError(
        event.error === "not-allowed"
          ? "Microphone permission was denied. Allow microphone access in your browser."
          : event.error === "no-speech"
            ? "No speech detected. Please try again."
            : "Voice recognition encountered an error. Please try again.",
      );

      setIsListening(false);
    };

    recognition.onend = () => {
      setIsListening(false);
      recognitionRef.current = null;
    };

    recognitionRef.current = recognition;

    try {
      recognition.start();
      setIsListening(true);
    } catch {
      recognitionRef.current = null;
      setIsListening(false);
      setVoiceError("Unable to start voice recognition. Please try again.");
    }
  }

  function stopVoiceInput() {
    recognitionRef.current?.stop();
    setIsListening(false);
  }

  const loadConversations = useCallback(async () => {
    try {
      const data = await apiRequest<Conversation[]>("/ai-coach/conversations");
      setConversations(data);
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to load conversation history."
      );
    } finally {
      setLoadingHistory(false);
    }
  }, []);

  useEffect(() => {
    void loadConversations();
  }, [loadConversations]);

  useEffect(() => {
    return () => {
      recognitionRef.current?.abort();
      recognitionRef.current = null;
    };
  }, []);

  const openConversation = async (id: string) => {
    setLoading(true);
    setError("");
    setEditingMessageId(null);
    setInput("");
    setVoiceError("");

    try {
      const data = await apiRequest<Message[]>(
        `/ai-coach/conversations/${id}/messages`
      );

      setMessages(data);
      setContextSummary(null);
      setActiveId(id);
      setTab("chat");
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unable to open conversation.");
    } finally {
      setLoading(false);
    }
  };

  const startNewChat = () => {
    setActiveId(null);
    setMessages([]);
    setContextSummary(null);
    setInput("");
    setError("");
    setTab("chat");
    setEditingMessageId(null);
    setVoiceError("");
    stopVoiceInput();
  };

  const sendMessage = async (
    event?: FormEvent<HTMLFormElement>,
    suggestedMessage?: string,
  ) => {
    event?.preventDefault();

    const content = (suggestedMessage ?? input).trim();

    if (!content || loading) return;

    setLoading(true);
    setError("");
    setVoiceError("");
    stopVoiceInput();

    const originalConversationId = activeId;
    const originalEditingMessageId = editingMessageId;

    let conversationId = activeId;
    let forkedConversationId: string | null = null;

    setInput("");

    try {
      // Editing creates a new branch, leaving the original conversation intact.
      if (originalEditingMessageId && originalConversationId) {
        const branch = await apiRequest<{ id: string }>(
          `/ai-coach/conversations/${originalConversationId}/messages/${originalEditingMessageId}/fork`,
          {
            method: "POST",
          },
        );

        conversationId = branch.id;
        forkedConversationId = branch.id;
      }

      // Create a conversation when starting a new chat.
      if (!conversationId) {
        const created = await apiRequest<{ id: string }>(
          "/ai-coach/conversations",
          {
            method: "POST",
            body: JSON.stringify({
              title: content.slice(0, 50),
            }),
          },
        );

        conversationId = created.id;
      }

      const result = await apiRequest<SendResponse>(
        `/ai-coach/conversations/${conversationId}/messages`,
        {
          method: "POST",
          body: JSON.stringify({
            content,
            includeJournal,
          }),
        },
      );

      setActiveId(conversationId);

      if (originalEditingMessageId) {
        // Keep the earlier messages and replace the edited branch.
        const selectedIndex = messages.findIndex(
          (message) => message.id === originalEditingMessageId,
        );

        setMessages([
          ...messages.slice(0, selectedIndex),
          result.userMessage,
          result.assistantMessage,
        ]);

        setEditingMessageId(null);
      } else {
        setMessages((current) => [
          ...current,
          result.userMessage,
          result.assistantMessage,
        ]);
      }

      setContextSummary(result.contextSummary);

      await loadConversations();
    } catch (err) {
      // Remove an incomplete branch if AI generation fails.
      if (forkedConversationId) {
        try {
          await apiRequest(
            `/ai-coach/conversations/${forkedConversationId}`,
            { method: "DELETE" },
          );
        } catch {
          // Keep the original conversation usable even if cleanup fails.
        }
      }

      setError(
        err instanceof Error
          ? err.message
          : "Unable to send your message.",
      );

      setInput(content);
    } finally {
      setLoading(false);
    }
  };

  const deleteConversation = async (id: string) => {
    if (!window.confirm("Delete this conversation permanently?")) return;

    try {
      await apiRequest(`/ai-coach/conversations/${id}`, {
        method: "DELETE",
      });

      setConversations((current) =>
        current.filter((conversation) => conversation.id !== id)
      );

      if (activeId === id) {
        startNewChat();
      }
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Unable to delete conversation."
      );
    }
  };

  return (
    <main className="coach-page">
      <header className="coach-header">
        <div className="coach-heading">
          <div className="coach-icon">✧</div>
          <div>
            <span className="coach-eyebrow">YOUR PERSONAL GROWTH COMPANION</span>
            <h1>AI Coach</h1>
            <p>Understand your progress. Make better decisions.</p>
          </div>
        </div>

        <button
          className="coach-new-chat"
          type="button"
          onClick={startNewChat}
          disabled={loading}
        >
          + New chat
        </button>
      </header>

      <nav className="coach-tabs">
        <button
          type="button"
          className={tab === "chat" ? "active" : ""}
          onClick={() => setTab("chat")}
        >
          <span>✧</span> Chat
        </button>

        <button
          type="button"
          className={tab === "history" ? "active" : ""}
          onClick={() => {
            setTab("history");
            void loadConversations();
          }}
        >
          <span>◷</span> History
          <span className="coach-history-count">{conversations.length}</span>
        </button>
      </nav>

      {error && (
        <div className="coach-error" role="alert">
          {error}
          <button type="button" onClick={() => setError("")}>Dismiss</button>
        </div>
      )}

      {tab === "history" ? (
        <section className="coach-history">
          <div className="coach-section-heading">
            <div>
              <h2>Your conversations</h2>
              <p>Continue where you left off.</p>
            </div>
            <button type="button" onClick={startNewChat}>+ New chat</button>
          </div>

          {loadingHistory ? (
            <div className="coach-empty">Loading conversations...</div>
          ) : conversations.length === 0 ? (
            <div className="coach-empty">
              <span>◷</span>
              <h3>No conversations yet</h3>
              <p>Your saved conversations will appear here.</p>
            </div>
          ) : (
            <div className="coach-history-list">
              {conversations.map((conversation) => (
                <article className="coach-history-item" key={conversation.id}>
                  <button
                    className="coach-history-open"
                    type="button"
                    onClick={() => void openConversation(conversation.id)}
                  >
                    <span className="coach-history-icon">✧</span>
                    <span className="coach-history-details">
                      <strong>{conversation.title}</strong>
                      <small>
                        {conversation.messages[0]?.content || "No messages yet"}
                      </small>
                      <small>
                        {new Date(conversation.updatedAt).toLocaleDateString(
                          "en-IN",
                          { day: "numeric", month: "short", year: "numeric" }
                        )}
                      </small>
                    </span>
                  </button>

                  <button
                    className="coach-delete"
                    type="button"
                    onClick={() => void deleteConversation(conversation.id)}
                    aria-label={`Delete ${conversation.title}`}
                  >
                    ×
                  </button>
                </article>
              ))}
            </div>
          )}
        </section>
      ) : (
        <section className="coach-chat">
          <div className="coach-messages">
            {messages.length === 0 ? (
              <div className="coach-welcome">
                <div className="coach-welcome-icon">✧</div>
                <h2>What would you like to work on?</h2>
                <p>
                  Your coach can use your AVIA goals, habits and plans to give
                  more relevant guidance.
                </p>

                <div className="coach-suggestions">
                  {suggestions.map((suggestion) => (
                    <button
                      key={suggestion}
                      type="button"
                      disabled={loading}
                      onClick={() => void sendMessage(undefined, suggestion)}
                    >
                      {suggestion}
                      <span>↗</span>
                    </button>
                  ))}
                </div>
              </div>
            ) : (
              messages.map((message) => (
                <div
                  className={`coach-message coach-message--${message.role}`}
                  key={message.id}
                >
                  {message.role === "assistant" && (
                    <span className="coach-avatar">✧</span>
                  )}
                  <div className="coach-message-content">
                    {message.role === "assistant" ? (
                      <ReactMarkdown
                        remarkPlugins={[remarkGfm]}
                        components={{
                          a: ({ children, href }) => (
                            <a
                              href={href}
                              target="_blank"
                              rel="noopener noreferrer"
                            >
                              {children}
                            </a>
                          ),

                          pre: ({ children }) => (
                            <div className="coach-markdown-pre">
                              {children}
                            </div>
                          ),

                          code: ({ children, className }) => {
                            if (className === "language-avia-plan") {
                              return <PlanCopyBlock>{children}</PlanCopyBlock>;
                            }

                            return <code className={className}>{children}</code>;
                          },
                        }}
                      >
                        {message.content}
                      </ReactMarkdown>
                    ) : (
                      message.content
                    )}

                    {message.role === "user" && (
                      <button
                        type="button"
                        className="coach-message-edit"
                        disabled={loading}
                        onClick={() => {
                          setEditingMessageId(message.id);
                          setInput(message.content);
                          setVoiceError("");
                          setError("");
                          setTab("chat");
                        }}
                      >
                        Edit
                      </button>
                    )}
                  </div>
                </div>
              ))
            )}

            {loading && (
              <div className="coach-message coach-message--assistant">
                <span className="coach-avatar">✧</span>
                <div className="coach-message-content coach-typing">
                  Thinking...
                </div>
              </div>
            )}
          </div>

          {contextSummary && (
            <div className="coach-context-panel">
              <div className="coach-context-heading">
                <span>✧</span>
                <strong>AVIA Context</strong>
                <small>Latest response</small>
              </div>

              <p>
                Your coach received the following information for its latest response.
              </p>

              <div className="coach-context-items">
                <span>{contextSummary.goals} active goals</span>
                <span>{contextSummary.urgentGoals} urgent goals</span>
                <span>{contextSummary.plannedTasks} planned tasks today</span>
                <span>{contextSummary.pendingTasks} pending tasks</span>
                <span>{contextSummary.habits} active habits</span>
                <span>{contextSummary.pendingHabits} pending daily habits</span>

                {contextSummary.journalIncluded && (
                  <span className="coach-context-journal">
                    Recent journal included
                  </span>
                )}
              </div>
            </div>
          )}

          <div className="coach-permission">
            <label>
              <input
                type="checkbox"
                checked={includeJournal}
                onChange={(event) => setIncludeJournal(event.target.checked)}
                disabled={loading}
              />
              Allow this message to use my recent journal entries
            </label>
            <span>Off by default</span>
          </div>

          {voiceError && (
            <div className="coach-voice-error" role="status">
              {voiceError}
              <button
                type="button"
                onClick={() => setVoiceError("")}
                aria-label="Dismiss voice input message"
              >
                ×
              </button>
            </div>
          )}

          <form
            className="coach-input-area"
            onSubmit={(event) => void sendMessage(event)}
          >
            {editingMessageId && (
              <div className="coach-editing-banner">
                <span>Editing an earlier message. Sending it creates a new conversation branch.</span>
                <button
                  type="button"
                  onClick={() => {
                    setEditingMessageId(null);
                    setInput("");
                  }}
                >
                  Cancel edit
                </button>
              </div>
            )}

            <textarea
              ref={inputRef}
              value={input}
              onChange={(event) => setInput(event.target.value)}
              placeholder="Ask your coach anything..."
              rows={2}
              maxLength={4000}
              disabled={loading}
              onKeyDown={(event) => {
                if (event.key === "Enter" && !event.shiftKey) {
                  event.preventDefault();
                  void sendMessage();
                }
              }}
            />

            <button
              type="button"
              className={`coach-mic-button ${isListening ? "is-listening" : ""}`}
              onClick={isListening ? stopVoiceInput : startVoiceInput}
              disabled={loading}
              aria-label={isListening ? "Stop voice input" : "Start voice input"}
              aria-pressed={isListening}
              title={isListening ? "Stop listening" : "Start voice input"}
            >
              {isListening ? "■" : "🎙"}
            </button>

            <button type="submit" disabled={loading || !input.trim()}>
              {loading ? "..." : "↑"}
            </button>

            <div className="coach-input-meta">
              <label htmlFor="coach-speech-language">Voice language</label>

              <select
                id="coach-speech-language"
                value={speechLanguage}
                onChange={(event) =>
                  setSpeechLanguage(event.target.value as SpeechLanguage)
                }
                disabled={loading || isListening}
              >
                <option value="en-IN">English</option>
                <option value="hi-IN">Hindi</option>
                <option value="mr-IN">Marathi</option>
              </select>

              <span>
                {isListening
                  ? "Listening... Speak now"
                  : "Enter to send · Shift + Enter for a new line"}
              </span>
            </div>
          </form>
        </section>
      )}

      <p className="coach-disclaimer">
        AI Coach can make mistakes. Use your judgment for important decisions.
      </p>
    </main>
  );
}